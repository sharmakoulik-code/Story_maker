test('pin a library design, import and approve the blue-flower frames, and replace one locally', { timeout: 100_000 }, async () => {
  assert.ok(executable, 'Set KOMA_CHROMIUM_EXECUTABLE to a local Chromium-family executable.')
  const root = await mkdtemp(join(tmpdir(), 'Koma visual smoke বাগান '))
  const sample = (await readFile(join(repo, 'tests', 'fixtures', 'blue_flower.txt'), 'utf8')).trim()
  const images = join(repo, 'backend', 'demo_art')
  const port = await freePort()
  const origin = `http://127.0.0.1:${port}`
  let stop = null, browser = null
  try {
    stop = await studio(root, port)
    browser = await chromium.launch({ executablePath: executable, headless: true, args: JSON.parse(process.env.KOMA_CHROMIUM_ARGS || '[]') })
    const page = await browser.newPage({ viewport: { width: 1440, height: 980 } })
    page.setDefaultTimeout(8_000)
    const errors = [], external = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error' && message.text().includes('Content Security Policy')) errors.push(message.text()) })
    await page.route('**/*', route => {
      if (new URL(route.request().url()).origin === origin) return route.continue()
      external.push(route.request().url())
      return route.abort('blockedbyclient')
    })
    const ui = (title) => page.getByRole('button', { name: title, exact: true })
    const shot = (number) => page.getByRole('button', { name: new RegExp(`^Select scene ${number}:`) })
    const getJson = async (url) => {
      const response = await page.request.get(url)
      assert.ok(response.ok(), await response.text())
      return response.json()
    }
    async function importPicture(button, file, message) {
      await ui(button).click()
      await page.getByLabel('Still image file').setInputFiles(join(images, file))
      await page.getByLabel('Asset source').fill('Koma original illustration')
      await page.getByLabel('License or usage rights').fill('CC0-1.0')
      await ui('Save local image').click()
      await page.getByText(message, { exact: false }).waitFor()
    }
    await page.goto(`${origin}/characters`)
    await visible(page, 'Character Library')
    await ui('New character').click()
    await page.getByLabel('Character name', { exact: true }).fill('Mina · Forest traveler')
    await page.getByLabel('Face', { exact: true }).fill('Soft round cheeks')
    await page.getByLabel('Hair', { exact: true }).fill('Plum bob')
    await page.getByLabel('Outfits', { exact: true }).fill('Mint coat')
    await page.getByLabel('Accessories', { exact: true }).fill('Gold star pin')
    await page.getByLabel('Generation instructions', { exact: true }).fill('Preserve the star pin across shots.')
    await ui('Save character').click()
    await page.getByText('Character saved to this library.', { exact: true }).waitFor()
    await importPicture('Import reference', 'traveler-reference.webp', 'Reference saved. Existing project pins did not change.')
    const [libraryEntry] = await getJson(`${origin}/api/characters`)
    assert.equal(libraryEntry.reference.number, 1)
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'New story' }).click()
    await visible(page, 'New story')
    await page.getByLabel('Project title').fill('The Blue Flower visuals test')
    await page.getByLabel(/Story text/).fill(sample)
    await page.getByLabel('Target duration').selectOption('30')
    await ui('Generate story plan').click()
    await visible(page, 'Story plan')
    await ui('Story Bible').click()
    const lead = page.locator('.bible-entry').filter({ has: page.getByRole('heading', { name: 'Little chibi girl', exact: true }) })
    await lead.getByText('Library design', { exact: true }).click()
    await lead.getByRole('combobox', { name: /Saved design for Little chibi girl/ }).selectOption(libraryEntry.id)
    await lead.getByRole('button', { name: 'Apply design to this character', exact: true }).click()
    await ui('Save plan').first().click()
    await page.getByText('Plan saved. Timing has been checked.').waitFor()
    const planApiURL = `${origin}/api${new URL(page.url()).pathname}`
    const pin = (await getJson(planApiURL)).plan.document.bible.characters[0].library_pin
    assert.equal(pin.image_id, libraryEntry.reference.id)
    await ui('Approve plan').click()
    await page.getByRole('link', { name: 'Open the storyboard', exact: true }).click()
    await visible(page, 'Storyboard')
    const boardURL = page.url()
    const boardApiURL = `${origin}/api${new URL(boardURL).pathname}`
    assert.equal(await page.locator('.shot-card').count(), 3)
    const importMessage = 'Still imported. Earlier versions and other scenes are unchanged.'
    for (const [index, file] of ['flower.webp', 'old-tree-study.webp', 'forest-lights.webp'].entries()) {
      await shot(index + 1).click()
      await importPicture('Import frame', file, importMessage)
      const ready = await getJson(boardApiURL)
      assert.ok(ready.shots[index].active.available)
    }
    await shot(1).click()
    await ui('Approve frame').click()
    await page.getByText('Frame approved.', { exact: true }).waitFor()
    await page.getByRole('checkbox', { name: 'Select scene 2 for approval', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Select scene 3 for approval', exact: true }).check()
    await ui('Approve selected (2)').click()
    await page.getByText('2 frames approved.', { exact: true }).waitFor()
    const reviewed = await getJson(boardApiURL)
    assert.deepEqual(reviewed.shots.map(row => row.status), ['approved', 'approved', 'approved'])
    await shot(2).click()
    await importPicture('Replace frame', 'old-tree.webp', importMessage)
    const replaced = await getJson(boardApiURL)
    assert.deepEqual(replaced.shots.map(row => row.status), ['approved', 'review', 'approved'])
    assert.deepEqual([replaced.shots[0], replaced.shots[2]], [reviewed.shots[0], reviewed.shots[2]])
    await page.getByText('Image versions', { exact: false }).click()
    await page.getByText(/Previously approved/).waitFor()
    await page.waitForFunction(() => {
      const thumbnails = [...document.querySelectorAll('.shot-card-image img')]
      return thumbnails.length === 3 && thumbnails.every(image => image.naturalWidth === 360)
    })
    await stop('SIGKILL')
    stop = await studio(root, port)
    await page.goto(boardURL)
    await visible(page, 'Storyboard')
    assert.deepEqual((await getJson(boardApiURL)).shots, replaced.shots)
    await shot(2).click()
    await page.getByText('Image versions', { exact: false }).click()
    await ui('Use version 1').click()
    await page.getByText('Image version selected. Review this frame again before approving it.', { exact: true }).waitFor()
    await ui('Approve frame').click()
    await page.getByText('Frame approved.', { exact: true }).waitFor()
    assert.equal((await getJson(boardApiURL)).shots[1].active.id, reviewed.shots[1].active.id)
    await ui('Scene details').click()
    await page.getByLabel('Camera direction').fill('A closer portrait of the spirit beneath the roots.')
    await ui('Move scene earlier').click()
    await ui('Add scene').click()
    await visible(page, 'New scene 4')
    const removal = page.waitForEvent('dialog')
    const removing = ui('Remove scene').click()
    await (await removal).accept()
    await removing
    await ui('Save scene edits').click()
    await page.getByText(/Scene edits saved/).waitFor()
    const reordered = await getJson(boardApiURL)
    assert.deepEqual(reordered.shots.map(row => row.status), ['changed', 'approved', 'approved'])
    assert.equal(reordered.shots[0].scene_id, replaced.shots[1].scene_id)
    assert.equal(reordered.shots[0].active.id, reviewed.shots[1].active.id)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Character Library' }).click()
    await visible(page, 'Character Library')
    await importPicture('Replace reference', 'creature-reference.webp', 'Reference saved. Existing project pins did not change.')
    await page.getByText('Reference versions', { exact: false }).filter({ hasText: '2' }).first().waitFor()
    const [altered] = await getJson(`${origin}/api/characters`)
    assert.equal(altered.reference.number, 2)
    assert.equal((await getJson(planApiURL)).plan.document.bible.characters[0].library_pin.image_id, libraryEntry.reference.id)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
    assert.deepEqual(external, [])
    assert.deepEqual(errors, [])
  } finally {
    await browser?.close()
    await stop?.()
    await rm(root, { recursive: true, force: true })
  }
})
