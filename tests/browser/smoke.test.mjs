test('create, import, edit, archive, configure, and reopen with no external requests', { timeout: 90_000 }, async () => {
  assert.ok(executable, 'Set KOMA_CHROMIUM_EXECUTABLE to a local Chrome, Edge, or Chromium executable.')
  const root = await mkdtemp(join(tmpdir(), 'Koma browser test '))
  const workspace = join(root, 'Local workspace গল্প')
  const port = await freePort()
  const origin = `http://127.0.0.1:${port}`
  let stop = null, browser = null
  try {
    stop = await studio(workspace, port)
    browser = await chromium.launch({ executablePath: executable, headless: true, args: JSON.parse(process.env.KOMA_CHROMIUM_ARGS || '[]') })
    const page = await browser.newPage({ viewport: { width: 1440, height: 980 } })
    page.setDefaultTimeout(8_000)
    const errors = [], external = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error' && message.text().includes('Content Security Policy')) errors.push(message.text()) })
    await page.route('**/*', route => {
      if (new URL(route.request().url()).origin === origin) return route.continue()
      external.push(route.request().url())
      return route.abort('blockedbyclient')
    })
    await page.goto(origin)
    await visible(page, 'Your first story belongs here')
    await page.getByText('Local only', { exact: true }).waitFor()
    await page.getByRole('link', { name: 'New story' }).first().click()
    await visible(page, 'New story')
    const story = 'A small lantern warms the forest.\nবনের আলো। जंगल की रोशनी।'
    await page.locator('input[type=file]').setInputFiles({ name: 'night-forest.txt', mimeType: 'text/plain', buffer: Buffer.concat([Buffer.from([0xFF, 0xFE]), Buffer.from(story, 'utf16le')]) })
    await page.getByText('Imported night-forest.txt').waitFor()
    assert.equal(await page.getByLabel(/Story text/).inputValue(), story)
    await page.getByLabel('Project title').fill('After the rain')
    const leaveAttempt = page.waitForEvent('dialog')
    const clickOverview = page.getByRole('link', { name: 'Overview', exact: true }).click()
    const confirm = await leaveAttempt
    assert.match(confirm.message(), /Leave without saving/)
    await confirm.dismiss()
    await clickOverview
    assert.equal(await page.getByLabel('Project title').inputValue(), 'After the rain')
    await page.getByLabel('Target duration').selectOption('custom')
    await page.getByLabel('Custom duration in seconds').fill('45')
    await page.getByLabel('Narration language').selectOption('bn')
    await page.getByLabel('Visual style').selectOption('cel')
    await page.getByLabel('Frame rate').selectOption('18')
    await page.getByRole('button', { name: /^subtle$/i }).click()
    await page.getByRole('button', { name: 'Create project' }).click()
    await visible(page, 'After the rain')
    const projectURL = page.url()
    const projectKey = new URL(projectURL).pathname
    assert.match(projectKey, /^\/projects\/[a-f0-9]{32}$/)
    const { folder } = await (await page.request.get(`${origin}/api${projectKey}`)).json()
    assert.ok((await stat(folder)).isDirectory())
    await page.getByLabel('Project title').fill('After the storm')
    await page.getByRole('button', { name: 'Save draft' }).click()
    await visible(page, 'After the storm')
    await page.getByText('Draft saved.', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Archive project' }).click()
    await page.getByText('Project archived. Its story and files are unchanged.').waitFor()
    assert.equal(await page.getByLabel('Project title').isEnabled(), false)
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'My projects' }).click()
    await visible(page, 'Your first story belongs here')
    await page.getByRole('button', { name: /^archived/i }).click()
    await visible(page, 'After the storm')
    await page.getByLabel('Search project titles').fill('unrelated')
    await visible(page, 'No matching projects')
    await page.getByRole('button', { name: 'Clear search', exact: true }).click()
    await visible(page, 'After the storm')
    await page.getByRole('link', { name: /After the storm/ }).click()
    await page.getByRole('button', { name: 'Restore project' }).click()
    await page.getByText('Project restored.', { exact: true }).waitFor()
    await page.getByRole('link', { name: 'System & models' }).click()
    await visible(page, 'Hardware details')
    await page.getByRole('button', { name: 'Refresh diagnostics' }).click()
    const newPath = join(workspace, 'New projects')
    await page.getByLabel('Projects folder').fill(newPath)
    await page.getByRole('button', { name: 'Save settings' }).click()
    await page.getByText('Local paths saved. Existing projects were not moved.').waitFor()
    await stop()
    stop = await studio(workspace, port)
    await page.goto(projectURL)
    await visible(page, 'After the storm')
    assert.equal(await page.getByLabel(/Story text/).inputValue(), story)
    assert.equal(await page.getByLabel('Custom duration in seconds').inputValue(), '45')
    assert.equal(await page.getByLabel('Narration language').inputValue(), 'bn')
    assert.equal(await page.getByLabel('Frame rate').inputValue(), '18')
    assert.equal((await (await page.request.get(`${origin}/api${projectKey}`)).json()).folder, folder)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
    await page.goto(`${origin}/settings`)
    await visible(page, 'Workspace paths')
    assert.equal(await page.getByLabel('Projects folder').inputValue(), newPath)
    assert.deepEqual(external, [])
    assert.deepEqual(errors, [])
  } finally {
    await browser?.close()
    await stop?.()
    await rm(root, { recursive: true, force: true })
  }
})

